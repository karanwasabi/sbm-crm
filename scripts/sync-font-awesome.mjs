#!/usr/bin/env node
/**
 * Copies Font Awesome 4 webfonts to public/ and emits CSS with stable /fonts/ URLs
 * so GrapesJS toolbar icons work in Next.js (npm CSS uses ../fonts/ which breaks when bundled).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const crmRoot = path.resolve(__dirname, '..');
const pkgRoot = path.join(crmRoot, 'node_modules/font-awesome');
const sourceFontsDir = path.join(pkgRoot, 'fonts');
const targetFontsDir = path.join(crmRoot, 'public/fonts/font-awesome');
const sourceCss = path.join(pkgRoot, 'css/font-awesome.min.css');
const targetCss = path.join(crmRoot, 'src/components/comms/grapes-font-awesome.css');

const FONT_FILES = [
  'fontawesome-webfont.eot',
  'fontawesome-webfont.woff2',
  'fontawesome-webfont.woff',
  'fontawesome-webfont.ttf',
  'fontawesome-webfont.svg',
];

function main() {
  if (!fs.existsSync(sourceCss)) {
    console.error('font-awesome not installed. Run: pnpm add font-awesome@4.7.0');
    process.exit(1);
  }

  fs.mkdirSync(targetFontsDir, { recursive: true });

  for (const file of FONT_FILES) {
    const src = path.join(sourceFontsDir, file);
    if (!fs.existsSync(src)) {
      console.warn(`Missing font file: ${file}`);
      continue;
    }
    fs.copyFileSync(src, path.join(targetFontsDir, file));
  }

  const css = fs.readFileSync(sourceCss, 'utf8').replaceAll('../fonts/', '/fonts/font-awesome/');
  const banner = `/* Generated by scripts/sync-font-awesome.mjs — do not edit */\n`;
  fs.writeFileSync(targetCss, banner + css);

  console.log(`Synced Font Awesome fonts to public/fonts/font-awesome/`);
  console.log(`Wrote ${path.relative(crmRoot, targetCss)}`);
}

main();
